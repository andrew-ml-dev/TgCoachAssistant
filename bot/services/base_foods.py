NUM = r"(\d+(?:[.,]\d+)?)"
UNIT = r"(г|гр|грамм\w*|шт|штук\w*|кус\w*)?\.?"


def item(b: Base, grams: float) -> dict:
    k = grams / 100
    return {"name": b.name, "grams": grams, "kcal": round(b.kcal * k, 1), "protein": round(b.protein * k, 1),
            "fat": round(b.fat * k, 1), "carbs": round(b.carbs * k, 1)}


def match(text: str) -> dict | None:
    """«творог 200 г», «200 г творога», «2 яйца», «огурец» — одна позиция из справочника, без Claude.

    Число без единиц: для штучных продуктов — штуки (если ≤ 10), иначе граммы. Без числа — штучный продукт = 1 шт.
    """
    t = normalize(text)
    for b in FOODS:
        for a in sorted(set(b.aliases + (b.name,)), key=len, reverse=True):
            n = re.escape(a)
            m = re.fullmatch(rf"{n}\s+{NUM}\s*{UNIT}", t) or re.fullmatch(rf"{NUM}\s*{UNIT}\s+{n}", t)
            if m:
                num = float(m.group(1).replace(",", "."))
                unit = m.group(2) or ""
                if unit.startswith(("шт", "кус")) or (not unit and b.piece and num <= 10):
                    if not b.piece:
                        return None
                    num *= b.piece
                return item(b, num) if 1 <= num <= 3000 else None
            if b.piece and re.fullmatch(n, t):
                return item(b, b.piece)
    return None
